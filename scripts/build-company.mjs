#!/usr/bin/env node
/**
 * Embeds company UI assets for the Vercel/Node runtime (and optional Cloudflare bundle).
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const css = readFileSync(path.join(root, 'worker/ui/style.css'), 'utf8');
/** Strip ESM exports so lib/whatsapp.mjs can run inside the public <script> bundle. */
const whatsappJs = readFileSync(path.join(root, 'lib/whatsapp.mjs'), 'utf8')
  .replace(/^export\s+/gm, '')
  .trim();
const publicJs = `${whatsappJs}\n${readFileSync(path.join(root, 'worker/ui/public.js'), 'utf8')}`;
const adminJs = readFileSync(path.join(root, 'worker/ui/admin.js'), 'utf8');
const asset = (name) =>
  `data:image/png;base64,${readFileSync(path.join(root, 'worker/assets', name)).toString('base64')}`;

const generated = `/** Auto-generated by scripts/build-company.mjs — do not edit. */
export const SITE_CSS = ${JSON.stringify(css)};
export const SITE_LOGO_LIGHT = ${JSON.stringify(asset('dkasu-logo-light.png'))};
export const SITE_LOGO_DARK = ${JSON.stringify(asset('dkasu-logo-dark.png'))};
export const SITE_ICON = ${JSON.stringify(asset('dkasu-icon.png'))};
export const PUBLIC_JS = ${JSON.stringify(publicJs)};
export const ADMIN_JS = ${JSON.stringify(adminJs)};
`;

mkdirSync(path.join(root, 'server'), { recursive: true });
writeFileSync(path.join(root, 'server/generated-assets.mjs'), generated);

// Keep Cloudflare reference bundle for rollback / comparison (not used by Vercel).
const core = readFileSync(path.join(root, 'worker/core.js'), 'utf8');
mkdirSync(path.join(root, 'dist/server'), { recursive: true });
writeFileSync(
  path.join(root, 'dist/server/index.js'),
  `const SITE_CSS=${JSON.stringify(css)};\nconst SITE_LOGO_LIGHT=${JSON.stringify(asset('dkasu-logo-light.png'))};\nconst SITE_LOGO_DARK=${JSON.stringify(asset('dkasu-logo-dark.png'))};\nconst SITE_ICON=${JSON.stringify(asset('dkasu-icon.png'))};\nconst PUBLIC_JS=${JSON.stringify(publicJs)};\nconst ADMIN_JS=${JSON.stringify(adminJs)};\n${core}`,
);

console.log('Built company assets for Vercel (server/generated-assets.mjs) and Cloudflare reference (dist/server/index.js)');
